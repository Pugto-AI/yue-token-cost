"""Generate BENCHMARK.md from bench/testset.json.

Deterministic: same input + same tiktoken version -> identical numbers.
Run: python bench/generate_benchmark.py
"""
import io
import json
import os
import statistics

import tiktoken

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SCRIPTS = [("en", "English"), ("zh_s", "简体"), ("zh_t", "繁體"), ("yue", "粵語")]


def analyze(enc, text):
    toks = enc.encode(text)
    partial = single = multi = 0
    for t in toks:
        raw = enc.decode_single_token_bytes(t)
        try:
            s = raw.decode("utf-8")
        except UnicodeDecodeError:
            partial += 1
            continue
        if len(s) == 1 and "\u4e00" <= s <= "\u9fff":
            single += 1
        elif len(s) >= 2 and all("\u4e00" <= c <= "\u9fff" for c in s):
            multi += 1
    return {
        "tokens": len(toks),
        "chars": len(text),
        "bytes": len(text.encode("utf-8")),
        "partial": partial,
        "single_cjk": single,
        "multi_cjk": multi,
    }


def main():
    with io.open(os.path.join(HERE, "testset.json"), encoding="utf-8") as f:
        ts = json.load(f)

    encs = {name: tiktoken.get_encoding(name) for name in ("o200k_base", "cl100k_base")}
    data = {}
    for item in ts["items"]:
        data[item["id"]] = {"label": item["label"], "scripts": {}}
        for key, _ in SCRIPTS:
            text = item[key]
            data[item["id"]]["scripts"][key] = {
                name: analyze(enc, text) for name, enc in encs.items()
            }
            data[item["id"]]["scripts"][key]["text"] = text

    L = []
    p = L.append

    p("# BENCHMARK")
    p("")
    p("Token cost of the **same meaning** written in four scripts, measured with real tokenizers.")
    p("")
    p("> Auto-generated by `bench/generate_benchmark.py` from `bench/testset.json`.")
    p("> Deterministic: same testset + same `tiktoken` version gives identical numbers.")
    p("> **Domain**: Hong Kong labour/legal enquiries. Sentences are hand-written per script, not machine-translated.")
    p("")

    p("## Matrix (tokens)")
    p("")
    header = "| Item | " + " | ".join(f"{label} ({key})" for key, label in SCRIPTS) + " |"
    p(header)
    p("|" + "---|" * (len(SCRIPTS) + 1))
    for item in ts["items"]:
        row = [item["label"]]
        for key, _ in SCRIPTS:
            row.append(str(data[item["id"]]["scripts"][key]["o200k_base"]["tokens"]))
        p("| " + " | ".join(row) + " |")
    p("")

    p("## Same matrix on the older tokenizer (`cl100k_base`, GPT-4 era)")
    p("")
    p(header)
    p("|" + "---|" * (len(SCRIPTS) + 1))
    for item in ts["items"]:
        row = [item["label"]]
        for key, _ in SCRIPTS:
            row.append(str(data[item["id"]]["scripts"][key]["cl100k_base"]["tokens"]))
        p("| " + " | ".join(row) + " |")
    p("")

    # totals and cost multipliers
    tot = {}
    for enc_name in encs:
        tot[enc_name] = {
            key: sum(data[i["id"]]["scripts"][key][enc_name]["tokens"] for i in ts["items"])
            for key, _ in SCRIPTS
        }
    p("## Totals and cost multipliers")
    p("")
    p("| Tokenizer | " + " | ".join(label for _, label in SCRIPTS) + " | 繁體/简体 | 粵語/简体 | 粵語/English |")
    p("|---|---|---|---|---|---|---|")
    for enc_name in encs:
        t = tot[enc_name]
        p(
            f"| `{enc_name}` | "
            + " | ".join(str(t[k]) for k, _ in SCRIPTS)
            + f" | {t['zh_t'] / t['zh_s']:.2f}x | {t['yue'] / t['zh_s']:.2f}x | {t['yue'] / t['en']:.2f}x |"
        )
    p("")
    for enc_name in encs:
        t = tot[enc_name]
        p(
            f"- `{enc_name}`: 繁體 costs **{(t['zh_t'] / t['zh_s'] - 1) * 100:.0f}%** more than 简体, "
            f"粵語 costs **{(t['yue'] / t['zh_s'] - 1) * 100:.0f}%** more than 简体 and "
            f"**{(t['yue'] / t['en'] - 1) * 100:.0f}%** more than English."
        )
    p("")
    p(
        f"- Tokenizer generation is a bigger lever than script: the identical 简体 text costs "
        f"**{tot['cl100k_base']['zh_s']} → {tot['o200k_base']['zh_s']}** tokens "
        f"({(1 - tot['o200k_base']['zh_s'] / tot['cl100k_base']['zh_s']) * 100:.0f}% cheaper) when moving "
        f"`cl100k_base` → `o200k_base`."
    )
    p("")

    p("## Attribution: why the extra tokens exist (`o200k_base`)")
    p("")
    p("`partial` = token whose bytes are not a whole UTF-8 character (a *half-character*, e.g. "
      "`饿` = `e9` | `a5 bf`). `single_cjk` = one whole Chinese character in one token. "
      "`multi_cjk` = several Chinese characters in one token (the cheap case).")
    p("")
    p("| Item | Script | tokens | partial | single_cjk | multi_cjk |")
    p("|---|---|---|---|---|---|")
    for item in ts["items"]:
        for key, label in SCRIPTS:
            a = data[item["id"]]["scripts"][key]["o200k_base"]
            p(f"| {item['label']} | {label} | {a['tokens']} | {a['partial']} | {a['single_cjk']} | {a['multi_cjk']} |")
    p("")

    part = {}
    for key, label in SCRIPTS:
        part[key] = sum(data[i["id"]]["scripts"][key]["o200k_base"]["partial"] for i in ts["items"])
        part[key + "_tok"] = sum(data[i["id"]]["scripts"][key]["o200k_base"]["tokens"] for i in ts["items"])
    p("Partial-character tokens by script (`o200k_base`): " + ", ".join(
        f"{label} {part[key]}/{part[key + '_tok']} ({part[key] / part[key + '_tok'] * 100:.1f}%)"
        for key, label in SCRIPTS
    ))
    p("")

    p("## Example splits")
    p("")
    for item in ts["items"]:
        for key, label in SCRIPTS:
            text = data[item["id"]]["scripts"][key]["text"]
            pieces = [encs["o200k_base"].decode([t]) for t in encs["o200k_base"].encode(text)]
            shown = " | ".join(repr(x) for x in pieces)
            p(f"- **{label}** (`{item['id']}`): {shown}")
    p("")

    p("## Reproduce")
    p("")
    p("```bash")
    p("pip install tiktoken")
    p("python bench/generate_benchmark.py")
    p("```")
    p("")
    p("## Scope and honesty notes")
    p("")
    p("- Measured tokenizers: `o200k_base` (GPT-4o and later) and `cl100k_base` (GPT-4 era). "
      "Local-model tokenizers (Qwen / Llama / Gemma) are **not** in this table yet; they need a "
      "downloadable HF tokenizer and will be added as separate rows, never mixed into one average.")
    p("- Ratios are computed over this 6-item testset only. They are **not** a universal constant: "
      "the driver is whether a word exists as a whole token in the vocabulary, not the language itself.")
    p("- No claim is made about pricing in HKD/USD: cost depends on the provider's per-token rate, "
      "which changes. Multiply by your own rate.")
    p("- Items marked with identical 简体/繁體 strings (e.g. `holiday-pay`) are kept deliberately: "
      "not every sentence differs between the two scripts, and a benchmark that hides this would overstate the gap.")
    p("")

    out = os.path.join(ROOT, "BENCHMARK.md")
    io.open(out, "w", encoding="utf-8").write("\n".join(L))
    print("wrote", out)
    print("o200k totals:", tot["o200k_base"])
    print("cl100k totals:", tot["cl100k_base"])


if __name__ == "__main__":
    main()
